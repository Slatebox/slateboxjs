import { expect, test } from '@playwright/test'

const origin = process.env.SLATEBOX_APP_URL || 'http://localhost:3000'

test('the saved field handoff supports safe undo and keeps another editor tab’s newer decision', async ({page,context}) => {
  test.skip(!['localhost','127.0.0.1','test.slatebox.com'].includes(new URL(origin).hostname), 'Private synthetic board on local or staging only')
  await page.goto(origin+'/new/offline-handoff?stage=review')
  await page.waitForURL(/\/canvas\/[a-f0-9]{10}$/)
  const scene = page.getByRole('region',{name:'Field handoff simulation'})
  await expect(scene).toHaveAttribute('data-stage','review')
  const welcome = page.getByRole('dialog',{name:/welcome/i})
  if (await welcome.isVisible()) await welcome.getByRole('button',{name:'OK'}).click()
  const cookies = page.locator('[data-cookie-notice] button')
  if (await cookies.isVisible()) await cookies.click()
  const second = await context.newPage()
  await second.goto(page.url())
  const other = second.getByRole('region',{name:'Field handoff simulation'})
  await expect(other).toHaveAttribute('data-stage','review')
  const undo = page.getByRole('button',{name:'Undo last change'})
  const changed = 'The reader missed the service badge.'
  await page.getByRole('textbox',{name:'Message Slatebox'}).fill('Set Field test to '+changed)
  await page.getByRole('button',{name:'Preview change'}).click()
  await expect(scene).toContainText(changed)
  await expect(other).not.toContainText(changed)
  await page.getByRole('button',{name:'Keep change'}).click()
  await expect(other).toContainText(changed)
  await scene.getByRole('button',{name:'Merge field test'}).click()
  await expect(other.getByRole('region',{name:'Published handoff'})).toContainText(changed)
  await undo.click()
  await expect(other).toHaveAttribute('data-stage','review')
  await expect(other).toContainText(changed)
  await expect(undo).toHaveCount(0)
  await scene.getByRole('button',{name:'Keep shared note'}).click()
  await expect(undo).toBeVisible()
  await other.getByRole('button',{name:'Reopen review'}).click()
  await expect(scene).toHaveAttribute('data-stage','review')
  await expect(undo).toHaveCount(0)
  await other.getByRole('button',{name:'Merge field test'}).click()
  await expect(scene).toHaveAttribute('data-stage','resolved')
  await page.reload()
  await expect(scene.getByRole('region',{name:'Published handoff'})).toContainText(changed)
  await page.getByRole('button',{name:'Present',exact:true}).click()
  const presentation=page.getByRole('dialog',{name:'Slate presentation'})
  await expect(presentation.getByRole('region',{name:'Published handoff'})).toContainText(changed)
  await expect(presentation.getByRole('button',{name:'Reopen review'})).toHaveCount(0)
  await presentation.getByRole('button',{name:'Exit presentation'}).click()
})
